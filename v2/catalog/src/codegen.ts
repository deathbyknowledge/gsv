// Generates the catalog's neutral exports: JSON Schema for every operation and frame, and the one version constant.
// `--check` fails when the committed output is stale.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";
import { ERROR_CODES, gsvErrorSchema } from "./errors.ts";
import { frameSchema, PROTOCOL } from "./frames.ts";
import { OPERATIONS } from "./ops.ts";

const out = new URL("../generated/", import.meta.url);

function schemaDocument(): string {
  const operations = Object.fromEntries(OPERATIONS.map(def => [def.name, {
    kind: def.kind,
    verb: def.verb,
    effect: def.effect,
    errors: def.errors,
    timeoutMs: def.timeoutMs,
    secretFields: def.secretFields,
    doc: def.doc,
    args: z.toJSONSchema(def.args, { io: "input" }),
    result: z.toJSONSchema(def.result),
  }]));
  const document = {
    protocol: PROTOCOL,
    errors: Object.fromEntries(Object.entries(ERROR_CODES).map(([code, entry]) => [code, entry])),
    error: z.toJSONSchema(gsvErrorSchema),
    frame: z.toJSONSchema(frameSchema, { io: "input" }),
    operations,
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

const schema = schemaDocument();
const version = createHash("sha256").update(schema).digest("hex").slice(0, 16);
const files = {
  "catalog.schema.json": schema,
  "version.ts": `// Generated by catalog/src/codegen.ts from the catalog's JSON Schema; do not edit.\nexport const CATALOG_VERSION = "${PROTOCOL}.${version}";\n`,
};

if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([name, text]) => {
    try { return readFileSync(new URL(name, out), "utf8") !== text; } catch { return true; }
  }).map(([name]) => name);
  if (stale.length) {
    console.error(`Stale catalog output: ${stale.join(", ")}. Run npm run catalog:generate.`);
    process.exit(1);
  }
} else {
  for (const [name, text] of Object.entries(files)) writeFileSync(new URL(name, out), text);
}
