import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import { createGenerator } from "ts-json-schema-generator";

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = join(toolDirectory, "..", "..");
const sourcePath = join(repositoryRoot, "packages", "gsv", "src", "protocol", "wire-frame.ts");
const tsconfigPath = join(repositoryRoot, "packages", "gsv", "tsconfig.json");
const outputPath = join(
  repositoryRoot,
  "workers",
  "gateway",
  "src",
  "protocol",
  "generated",
  "wire-frame-schema.js",
);
const schemaId = "https://gsv.dev/protocol/wire-frame.schema.json";

const schema = createGenerator({
  path: sourcePath,
  tsconfig: tsconfigPath,
  type: "WireValidationRoots",
  expose: "export",
  jsDoc: "extended",
  additionalProperties: false,
}).createSchema("WireValidationRoots");
schema.$id = schemaId;
const requestSchema = schema.definitions.WireRequestFrame;
const routedResponseSchema = schema.definitions.WireRoutedResponse;
const requestSchemaRefs = schemaReferences(
  requestSchema.anyOf,
  "WireRequestFrame",
);
const responseSchemaRefs = schemaReferences(
  routedResponseSchema.anyOf,
  "WireRoutedResponse",
);

const ajv = new Ajv({
  allErrors: false,
  strict: true,
  allowUnionTypes: true,
});
ajv.compile(schema);
const generated = [
  "// Generated by tools/protocol/generate-gateway-wire-validator.mjs.",
  "// Do not edit by hand.",
  `export const wireProtocolSchema = ${JSON.stringify(schema)};`,
  `export const wireRequestSchemaRefs = new Map(${JSON.stringify(requestSchemaRefs)});`,
  `export const wireResponseSchemaRefs = new Map(${JSON.stringify(responseSchemaRefs)});`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("Gateway wire-frame validator is stale; run npm run protocol:generate");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
}

function schemaReferences(branches, definitionName) {
  if (!Array.isArray(branches)) {
    throw new Error(`${definitionName} must be a union`);
  }
  return branches.map((branch, index) => {
    const call = branch.properties?.call?.const;
    if (!call) {
      throw new Error(`${definitionName} branch ${index} has no literal call`);
    }
    return [
      call,
      `${schemaId}#/definitions/${definitionName}/anyOf/${index}`,
    ];
  });
}
