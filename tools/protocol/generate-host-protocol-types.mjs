import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createGenerator } from "ts-json-schema-generator";

/**
 * Emit the Rust mirrors of the SDK protocol types the host applications carry
 * on the wire. Names, nesting, and optionality come from the TypeScript source
 * through its JSON schema; numeric widths are the one thing TypeScript cannot
 * say, so every number field is listed below and an unlisted one fails.
 */

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = join(toolDirectory, "..", "..");
const sourcePath = join(repositoryRoot, "packages", "gsv", "src", "protocol", "index.ts");
const tsconfigPath = join(repositoryRoot, "packages", "gsv", "tsconfig.json");
const outputPath = join(
  repositoryRoot,
  "host",
  "crates",
  "gateway-client",
  "src",
  "protocol",
  "generated.rs",
);

/** SDK type, its Rust name, and Rust names for the anonymous objects nested in it. */
const ROOTS = [
  { type: "FrameError", rust: "ErrorShape" },
  { type: "BinaryFrameDescriptor", rust: "FrameBodyDescriptor", copy: true },
  { type: "ProcessIdentity", rust: "ProcessIdentity" },
  { type: "PeerPrincipalKind", rust: "PeerPrincipalKind", copy: true },
  { type: "PeerPrincipal", rust: "PeerPrincipal" },
  { type: "PeerGrant", rust: "PeerGrant" },
  { type: "ConnectedPeer", rust: "ConnectedPeer" },
  { type: "ConnectArgs", rust: "ConnectArgs", inline: { peer: "PeerInfo", auth: "AuthInfo" } },
  { type: "ConnectResult", rust: "ConnectResult", inline: { server: "ServerInfo" } },
  { type: "ToolDefinition", rust: "ToolDefinition" },
];

const NUMBER_WIDTHS = {
  "FrameError.code": "i32",
  "BinaryFrameDescriptor.streamId": "u32",
  "BinaryFrameDescriptor.length": "u64",
  "ProcessIdentity.uid": "u64",
  "ProcessIdentity.gid": "u64",
  "ProcessIdentity.gids": "u64",
  "ConnectArgs.protocol": "u32",
  "ConnectResult.protocol": "u32",
};

const JSON_VALUE_TYPES = new Set(["JsonValue", "JsonObject", "JsonPrimitive"]);
const RUST_KEYWORDS = new Set(["type", "match", "ref", "self", "use", "mod", "move", "box"]);

const generator = createGenerator({
  path: sourcePath,
  tsconfig: tsconfigPath,
  expose: "export",
  jsDoc: "extended",
  additionalProperties: false,
  skipTypeCheck: true,
});

const rustNames = new Map(ROOTS.map((root) => [root.type, root.rust]));
const items = [];
for (const root of ROOTS) {
  const schema = generator.createSchema(root.type);
  const definition = schema.definitions[root.type];
  if (!definition) throw new Error(`${root.type} has no schema definition`);
  emitType(root.rust, definition, root.type, root.inline ?? {}, Boolean(root.copy));
}

const generated = [
  "// Generated by tools/protocol/generate-host-protocol-types.mjs from",
  "// packages/gsv/src/protocol. Do not edit by hand; run npm run protocol:generate.",
  "",
  "use serde::{Deserialize, Serialize};",
  "use serde_json::Value;",
  "",
  ...items,
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("Host protocol types are stale; run npm run protocol:generate");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
}

function emitType(rustName, definition, typePath, inline, copy) {
  if (definition.type === "string" && Array.isArray(definition.enum)) {
    emitEnum(rustName, definition, copy);
    return;
  }
  if (definition.type !== "object" || !definition.properties) {
    throw new Error(`${typePath} is neither an object nor a string enum`);
  }
  const required = new Set(definition.required ?? []);
  const fields = [];
  const nested = [];
  let camelCase = false;
  for (const [jsonName, property] of Object.entries(definition.properties)) {
    const fieldPath = `${typePath}.${jsonName}`;
    const snake = snakeCase(jsonName);
    if (snake !== jsonName) {
      if (camelCaseOf(snake) !== jsonName) {
        throw new Error(`${fieldPath} is not camelCase; add a rename rule`);
      }
      camelCase = true;
    }
    const isOptional = !required.has(jsonName);
    const resolved = fieldType(property, fieldPath, inline, jsonName, nested);
    const lines = [];
    if (property.description) lines.push(...docLines(property.description));
    let type = resolved;
    if (isOptional && resolved.startsWith("Vec<")) {
      lines.push('    #[serde(default, skip_serializing_if = "Vec::is_empty")]');
    } else if (isOptional) {
      lines.push('    #[serde(default, skip_serializing_if = "Option::is_none")]');
      type = `Option<${resolved}>`;
    }
    const fieldName = RUST_KEYWORDS.has(snake) ? `r#${snake}` : snake;
    lines.push(`    pub ${fieldName}: ${type},`);
    fields.push(lines.join("\n"));
  }
  const block = [];
  if (definition.description) block.push(...docLines(definition.description, ""));
  block.push(derive(copy));
  if (camelCase) block.push('#[serde(rename_all = "camelCase")]');
  block.push(`pub struct ${rustName} {`);
  block.push(fields.join("\n"));
  block.push("}", "");
  items.push(block.join("\n"));
  for (const child of nested) emitType(child.rustName, child.definition, child.typePath, {}, false);
}

function emitEnum(rustName, definition, copy) {
  const block = [];
  if (definition.description) block.push(...docLines(definition.description, ""));
  block.push(derive(copy));
  block.push(`pub enum ${rustName} {`);
  for (const value of definition.enum) {
    block.push(`    #[serde(rename = "${value}")]`);
    block.push(`    ${pascalCase(value)},`);
  }
  block.push("}", "");
  items.push(block.join("\n"));
}

function fieldType(property, fieldPath, inline, jsonName, nested) {
  if (property.$ref) {
    const target = decodeURIComponent(property.$ref.replace(/^#\/definitions\//, ""));
    if (JSON_VALUE_TYPES.has(target)) return "Value";
    const rust = rustNames.get(target);
    if (!rust) throw new Error(`${fieldPath} references ${target}, which is not a generated root`);
    return rust;
  }
  switch (property.type) {
    case "string":
      return "String";
    case "boolean":
      return "bool";
    case "number":
    case "integer": {
      const width = NUMBER_WIDTHS[fieldPath];
      if (!width) throw new Error(`${fieldPath} is a number without a width in NUMBER_WIDTHS`);
      return width;
    }
    case "array":
      return `Vec<${fieldType(property.items, fieldPath, inline, jsonName, nested)}>`;
    case "object": {
      const rustName = inline[jsonName];
      if (!rustName) throw new Error(`${fieldPath} is an anonymous object without a Rust name`);
      nested.push({ rustName, definition: property, typePath: fieldPath });
      return rustName;
    }
    default:
      throw new Error(`${fieldPath} has an unsupported schema: ${JSON.stringify(property)}`);
  }
}

function derive(copy) {
  return copy
    ? "#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]"
    : "#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]";
}

function docLines(description, indent = "    ") {
  return description.split("\n").map((line) => `${indent}/// ${line}`.trimEnd());
}

function snakeCase(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

function camelCaseOf(snake) {
  return snake.replace(/_([a-z0-9])/g, (_, letter) => letter.toUpperCase());
}

function pascalCase(value) {
  return value.split(/[-_]/).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
}
